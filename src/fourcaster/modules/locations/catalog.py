CATALOG: dict[str, Location] = {
    loc_id: Location(
        id=loc_id,
        name=name,
        coord=Coordinate(lat, lon),
        elevation_m=elevation,
        cluster=cluster,
        conf=conf,
        is_draft=(conf == "L"),      # FR-LOC-5
    )
    for loc_id, name, lat, lon, elevation, cluster, conf in _SEED
}


def published() -> dict[str, Location]:
    """Локации, которые можно показывать и считать (без черновых, FR-LOC-5)."""
    return {k: v for k, v in CATALOG.items() if not v.is_draft}


def get_location(location_id: str) -> Location:
    try:
        return CATALOG[location_id]
    except KeyError:
        raise KeyError(
            f"Локация '{location_id}' не найдена. Доступны: {', '.join(published())}"
        ) from None
